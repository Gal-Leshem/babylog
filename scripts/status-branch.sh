#!/usr/bin/env bash
# Maintains the public "ci-status" branch in the .ci-status worktree.
# It holds sanitized CI reports and the (non-secret) Apps Script project ids.
# The cloud sandbox cannot read GitHub Actions logs, so this branch is how results reach it.
#   init                 create/attach the worktree
#   publish "<message>"  commit and push, retrying on races
set -euo pipefail
DIR=".ci-status"
BRANCH="ci-status"
cmd="${1:?usage: status-branch.sh init|publish [message]}"

case "$cmd" in
  init)
    if [ -d "$DIR" ]; then exit 0; fi
    if git ls-remote --exit-code --heads origin "$BRANCH" >/dev/null 2>&1; then
      git fetch -q --depth=1 origin "$BRANCH"
      git worktree add -q -f -B "$BRANCH" "$DIR" FETCH_HEAD
    else
      git worktree add -q -f --detach "$DIR"
      (cd "$DIR" && git checkout -q --orphan "$BRANCH" && git rm -rfq --ignore-unmatch . && \
        printf 'Sanitized CI reports (reports/) and Apps Script project ids (envs/). Generated by the pipeline.\n' > README.md && \
        git add README.md && git commit -q -m "init ci-status")
    fi
    mkdir -p "$DIR/reports" "$DIR/envs"
    ;;
  publish)
    msg="${2:-update}"
    cd "$DIR"
    git add -A
    if git diff --cached --quiet; then exit 0; fi
    git commit -q -m "$msg"
    for i in 1 2 3 4 5 6; do
      if git push -q origin "HEAD:refs/heads/$BRANCH"; then exit 0; fi
      git fetch -q origin "$BRANCH" && { git rebase -q FETCH_HEAD || git rebase --abort; }
      sleep $((i * 2))
    done
    echo "could not publish $BRANCH" >&2
    exit 1
    ;;
  *) echo "unknown command $cmd" >&2; exit 2 ;;
esac
